// Dev only. Reads the vendored Coolify specs in vendor/coolify/ and writes
// src/backend/coolify/generated/operations.ts (OPERATIONS and
// EXCLUDED_OPERATIONS). Run with `npm run gen:coolify` after updating a spec,
// then update docs/coverage.md.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const root = fileURLToPath(new URL("..", import.meta.url));
const vendorDir = `${root}vendor/coolify/`;
const outDir = `${root}src/backend/coolify/generated/`;

// Oldest first. An operation's source is the oldest spec that has it.
// minVersion is the first Coolify version that can carry it: the v4.7.5 spec is
// treated as available from 4.4.0, the supported floor, and older instances
// that lack an endpoint are caught by 404/405 feature detection at call time.
const SOURCES = [
  { source: "4.7.5", file: "openapi-v4.7.5.json", minVersion: "4.4.0" },
  { source: "main", file: "openapi-main.json", minVersion: "4.7.6" },
  { source: "next", file: "openapi-next.json", minVersion: "4.8.0" },
];

// Operations no code path may dispatch, found by method and path so a renamed
// operationId still lands here.
const EXCLUDED = [
  {
    method: "POST",
    path: "/disable",
    why: "turns the API off and locks the plugin out",
  },
];

const METHODS = ["get", "post", "put", "patch", "delete"];
const VERSION = /^\d+\.\d+\.\d+$/;

function fail(message) {
  console.error(`gen-coolify-client: ${message}`);
  process.exit(1);
}

function compareVersions(a, b) {
  const pa = a.split(".").map(Number);
  const pb = b.split(".").map(Number);
  for (let i = 0; i < 3; i++) {
    if (pa[i] !== pb[i]) return pa[i] - pb[i];
  }
  return 0;
}

function readOperations(file) {
  const spec = JSON.parse(readFileSync(vendorDir + file, "utf8"));
  const seen = new Map();
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    for (const method of METHODS) {
      const operation = item[method];
      if (!operation) continue;
      const id = operation.operationId;
      if (!id)
        fail(`${file}: ${method.toUpperCase()} ${path} has no operationId`);
      if (seen.has(id)) fail(`${file}: operationId ${id} is used twice`);
      seen.set(id, { id, method: method.toUpperCase(), path });
    }
  }
  return seen;
}

const union = new Map();
for (const { source, file, minVersion } of SOURCES) {
  for (const operation of readOperations(file).values()) {
    const known = union.get(operation.id);
    if (!known) {
      union.set(operation.id, { ...operation, source, minVersion });
    } else if (
      known.method !== operation.method ||
      known.path !== operation.path
    ) {
      fail(
        `${operation.id} is ${known.method} ${known.path} in ${known.source} but ` +
          `${operation.method} ${operation.path} in ${source}; decide by hand which one to use`,
      );
    }
  }
}

// Hand-written overrides, for operations known to need a later version.
const overrides = JSON.parse(
  readFileSync(`${root}scripts/min-versions.json`, "utf8"),
);
for (const [id, version] of Object.entries(overrides)) {
  const operation = union.get(id);
  if (!operation) fail(`min-versions.json names ${id}, which no spec has`);
  if (!VERSION.test(version))
    fail(`min-versions.json: ${id} has bad version ${version}`);
  if (compareVersions(version, operation.minVersion) < 0) {
    fail(
      `min-versions.json: ${id} ${version} is older than its source's ${operation.minVersion}`,
    );
  }
  operation.minVersion = version;
}

const excludedIds = EXCLUDED.map(({ method, path }) => {
  const match = [...union.values()].find(
    (o) => o.method === method && o.path === path,
  );
  if (!match) fail(`excluded operation ${method} ${path} is in no spec`);
  return match.id;
});

const operations = [...union.values()].sort((a, b) =>
  a.id < b.id ? -1 : a.id > b.id ? 1 : 0,
);
const header =
  "// Generated by scripts/gen-coolify-client.mjs from vendor/coolify/*.json. Do not edit.\n" +
  "// Run `npm run gen:coolify` after updating a spec.\n";

const operationsTs = `${header}
export interface CoolifyOperation {
  id: string;
  method: "GET" | "POST" | "PATCH" | "PUT" | "DELETE";
  path: string;
  /** The oldest vendored spec that has the operation. */
  source: "4.7.5" | "main" | "next";
  /** The first Coolify version that can carry it (see meetsMinVersion). */
  minVersion: string;
}

export const OPERATIONS: readonly CoolifyOperation[] = ${JSON.stringify(
  operations.map(({ id, method, path, source, minVersion }) => ({
    id,
    method,
    path,
    source,
    minVersion,
  })),
)};

/**
 * Operation ids no code path may dispatch.
${EXCLUDED.map((e, i) => ` * - ${excludedIds[i]} (${e.method} ${e.path}): ${e.why}.`).join("\n")}
 */
export const EXCLUDED_OPERATIONS: ReadonlySet<string> = new Set(${JSON.stringify(excludedIds)});
`;

async function write(name, text) {
  const file = outDir + name;
  const options = (await prettier.resolveConfig(file)) ?? {};
  writeFileSync(
    file,
    await prettier.format(text, { ...options, filepath: file }),
  );
  console.log(`wrote ${file.slice(root.length)}`);
}

mkdirSync(outDir, { recursive: true });
await write("operations.ts", operationsTs);

const counts = Object.fromEntries(SOURCES.map(({ source }) => [source, 0]));
for (const operation of operations) counts[operation.source]++;
console.log(
  `${operations.length} operations: ${SOURCES.map(({ source }) => `${source} ${counts[source]}`).join(", ")}`,
);
